"""A deterministic synthetic box-tracking dataset and its adapter (tests and contract examples only).

Fixed data, no randomness, no download. ``write_source`` writes a source tree shaped like a real release —
native label files per sequence (pixel ``x1 y1 x2 y2`` boxes, native track ids and classes, a per-object
``ignore`` flag) and frame images (tiny binary PPMs) — so the descriptor, manifest, mapping and discovery paths
run exactly as they will for a real dataset. ``SyntheticAdapter`` reads it back through the verified manifest into
canonical ground truth: per sequence, the labelled instants and the GT tracks as ``{gtTrackId, nativeClass,
frames[] {frameIndex, videoOffsetMs, box {x, y, width, height} (normalised), ignore}}`` — the plan §7 input shape
with the native class still present (the association slice strips it before association). ``videoOffsetMs`` is an
exact rational ``{numerator, denominator}`` (plan §7.1), never a rounded float.
"""

from __future__ import annotations

import copy
import re
from pathlib import Path
from typing import Any, Iterable

from tools.benchmarks.core import descriptor as descriptors
from tools.benchmarks.core.identity import canonical_json, document_sha256, rational, require

# gtTrackId in benchmark-association-v1 (identifier, at most 256 characters).
GT_TRACK_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:/-]{0,255}")
ADAPTER_ID = "synthetic"
ADAPTER_VERSION = "1"
DATASET_ID = "synthetic-vehicles"
RELEASE = "synthetic-v1"
WIDTH, HEIGHT = 32, 18
FPS = (5, 1)
TAXONOMY = (
    ("car", "Car", "Synthetic: a passenger car."),
    ("minibus", "Minibus", "Synthetic: a small bus (a subset of the MAVI bus class)."),
    ("motorcycle", "Motorcycle", "Synthetic: a two-wheeled motor vehicle."),
    ("pedestrian", "Pedestrian", "Synthetic: a person on foot (not a Vehicle)."),
    ("truck", "Truck", "Synthetic: a goods vehicle."),
    ("van", "Van", "Synthetic: a van whose body type is not resolved."),
)
MAPPINGS = (
    ("car", "car", "exact", None, "Synthetic definition coincides with the MAVI class."),
    ("minibus", "bus", "subset", None, "Every minibus is a bus; not every bus is a minibus."),
    ("motorcycle", "motorcycle", "exact", None, "Synthetic definition coincides with the MAVI class."),
    ("pedestrian", None, "unsupported", "outside-capability", "Not a Vehicle in MAVI's broad class."),
    ("truck", "truck", "exact", None, "Synthetic definition coincides with the MAVI class."),
    ("van", None, "unsupported", "vehicle-unresolved", "Van body type is not resolved in the native labels."),
)
# split -> sequence -> frame count, tracks: (native id, class, first frame, last frame, x1, y1, w, h, dx, dy, ignored)
SEQUENCES: dict[str, dict[str, tuple[int, tuple[tuple[Any, ...], ...]]]] = {
    "val": {
        "seq-a": (8, (("1", "car", 0, 7, 1, 2, 6, 4, 2, 0, ()),
                      ("2", "truck", 2, 7, 20, 10, 8, 5, -1, 0, ()),
                      ("3", "pedestrian", 0, 4, 28, 1, 2, 5, 0, 1, (3,)))),
        "seq-b": (6, (("7", "minibus", 0, 5, 2, 8, 10, 6, 3, 0, ()),
                      ("9", "van", 1, 5, 15, 3, 7, 5, 0, 1, ()),
                      ("11", "motorcycle", 0, 3, 25, 12, 3, 3, -2, 0, ()))),
    },
    "train": {
        "seq-c": (4, (("1", "car", 0, 3, 4, 4, 6, 4, 1, 1, ()),)),
    },
}
SPLITS = (("train", True, "training"), ("val", True, "evaluation"))


def descriptor(entries: Iterable[dict[str, Any]] = ()) -> dict[str, Any]:
    """The release descriptor; unfrozen (empty manifest) unless ``entries`` are given."""
    document = {
        "schemaVersion": descriptors.SCHEMA,
        "datasetId": DATASET_ID,
        "datasetName": "Synthetic vehicles",
        "release": RELEASE,
        "task": "box-tracking",
        "source": {"kind": "official", "url": "https://mavi.local/synthetic-vehicles",
                   "retrievedOn": "2026-10-04"},
        "access": {"mechanism": "direct", "preconditions": []},
        "intendedUse": "development-benchmarking",
        "researchUse": {"status": "RESEARCH-ADMISSIBLE", "basis": "Synthetic data generated by the test suite.",
                        "termsReference": "tools/benchmarks/datasets/synthetic.py",
                        "redistribution": "not-permitted-by-default"},
        "splits": [{"name": name, "labelled": labelled, "role": role} for name, labelled, role in SPLITS],
        "nativeTaxonomy": [{"code": code, "name": name, "definition": definition}
                           for code, name, definition in TAXONOMY],
        "frameTime": {"kind": "index-at-fps", "fpsNumerator": FPS[0], "fpsDenominator": FPS[1]},
        "manifest": {"kind": "file-hashes", "entries": [dict(entry) for entry in entries]},
        "exposure": {"status": "none-known", "basis": "Synthetic data; no MAVI component has seen it."},
    }
    return descriptors.check(document)


def mapping() -> dict[str, Any]:
    rows = []
    for native, mavi, kind, unsupported, reason in MAPPINGS:
        row = {"nativeClass": native, "maviClass": mavi, "kind": kind, "reason": reason,
               "evaluation": {"exact": "scored", "subset": "subset-conditional", "unsupported": "excluded"}[kind]}
        if unsupported is not None:
            row["unsupportedKind"] = unsupported
        rows.append(row)
    return {"schemaVersion": "benchmark-class-mapping-v1", "datasetId": DATASET_ID, "release": RELEASE,
            "capability": "mavi-vehicle-subclass-v1", "mappings": rows}


# Source tree


def _frame_bytes(split: str, sequence: str, index: int) -> bytes:
    salt = sum(map(ord, f"{split}/{sequence}"))
    pixels = bytes((x * 7 + y * 13 + index * 31 + salt + channel * 101) % 256
                   for y in range(HEIGHT) for x in range(WIDTH) for channel in range(3))
    return f"P6\n{WIDTH} {HEIGHT}\n255\n".encode("ascii") + pixels


def _labels(sequence: str, frames: int, tracks: tuple[tuple[Any, ...], ...]) -> dict[str, Any]:
    rows = []
    for index in range(frames):
        objects = []
        for native_id, category, first, last, x1, y1, w, h, dx, dy, ignored in tracks:
            if first <= index <= last:
                step = index - first
                left, top = x1 + dx * step, y1 + dy * step
                objects.append({"id": native_id, "category": category,
                                "box": [left, top, left + w, top + h], "ignore": index in ignored})
        rows.append({"index": index, "objects": sorted(objects, key=lambda item: item["id"])})
    return {"sequence": sequence, "width": WIDTH, "height": HEIGHT, "frames": rows}


def annotation_path(split: str, sequence: str) -> str:
    return f"annotations/{split}/{sequence}.json"


def frame_path(split: str, sequence: str, index: int) -> str:
    return f"frames/{split}/{sequence}/{index:06d}.ppm"


def source_files() -> dict[str, bytes]:
    """Every source file of the synthetic release, by relative path."""
    files: dict[str, bytes] = {}
    for split, sequences in SEQUENCES.items():
        for sequence, (frames, tracks) in sequences.items():
            files[annotation_path(split, sequence)] = canonical_json(_labels(sequence, frames, tracks))
            for index in range(frames):
                files[frame_path(split, sequence, index)] = _frame_bytes(split, sequence, index)
    return files


def write_source(root: Path) -> Path:
    root = Path(root)
    for relative, data in sorted(source_files().items()):
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return root


# Adapter


class SyntheticAdapter:
    adapter_id = ADAPTER_ID
    adapter_version = ADAPTER_VERSION

    def native_classes(self) -> set[str]:
        return {code for code, _, _ in TAXONOMY}

    def sequences_described(self, manifest_paths: Iterable[str], split: str) -> list[str]:
        found = set()
        for path in manifest_paths:
            parts = path.split("/")
            if len(parts) == 3 and parts[0] == "annotations" and parts[1] == split and parts[2].endswith(".json"):
                found.add(parts[2].removesuffix(".json"))
            elif len(parts) == 4 and parts[0] == "frames" and parts[1] == split:
                found.add(parts[2])
        return sorted(found)

    def discover(self, source_root: Path, entries: dict[str, dict[str, Any]], split: str) -> list[str]:
        """A sequence is complete when its annotation file and every frame it labels are manifest members."""
        complete = []
        for sequence in self.sequences_described(entries, split):
            if annotation_path(split, sequence) not in entries:
                continue
            labels = self._labels(source_root, entries, split, sequence)
            if all(frame_path(split, sequence, row["index"]) in entries for row in labels["frames"]):
                complete.append(sequence)
        return complete

    def frame_paths(self, source_root: Path, entries: dict[str, dict[str, Any]], split: str,
                    sequence: str) -> list[tuple[int, str]]:
        """``(frameIndex, manifest path)`` of every labelled frame image, in index order (the derived video)."""
        labels = self._labels(source_root, entries, split, sequence)
        return [(row["index"], frame_path(split, sequence, row["index"])) for row in labels["frames"]]

    def _labels(self, source_root: Path, entries: dict[str, dict[str, Any]], split: str,
                sequence: str) -> dict[str, Any]:
        from tools.benchmarks.core._stage3 import artefacts

        data = descriptors.read_verified(entries, source_root, annotation_path(split, sequence))
        labels = artefacts.parse_json(data, f"adapter_label_invalid:{sequence}")
        require(isinstance(labels, dict) and labels.get("sequence") == sequence
                and labels.get("width") == WIDTH and labels.get("height") == HEIGHT
                and isinstance(labels.get("frames"), list), f"adapter_label_invalid:{sequence}")
        # Every nested record is checked here, so malformed labels are a refusal, never a KeyError or TypeError.
        for row in labels["frames"]:
            require(isinstance(row, dict) and type(row.get("index")) is int and row["index"] >= 0
                    and isinstance(row.get("objects"), list)
                    and all(isinstance(item, dict) for item in row["objects"]),
                    f"adapter_label_invalid:{sequence}:frame")
        return labels

    def ground_truth(self, source_root: Path, entries: dict[str, dict[str, Any]], descriptor: dict[str, Any],
                     split: str, sequence_id: str) -> dict[str, Any]:
        labels = self._labels(source_root, entries, split, sequence_id)
        classes = self.native_classes()
        instants, tracks = [], {}
        previous = -1
        for row in labels["frames"]:
            index = row.get("index")
            require(type(index) is int and index > previous, f"adapter_label_invalid:{sequence_id}:frame_order")
            previous = index
            require(frame_path(split, sequence_id, index) in entries, f"adapter_frame_missing:{sequence_id}:{index}")
            offset = rational(descriptors.index_offset_ms(descriptor, index))
            instants.append({"frameIndex": index, "videoOffsetMs": offset})
            seen: set[str] = set()
            for item in row.get("objects", []):
                # The native id becomes the gtTrackId of benchmark-association-v1, so it must satisfy that
                # contract, and one identity has at most one box per labelled instant: never deduplicated.
                native_id = item.get("id")
                require(isinstance(native_id, str) and GT_TRACK_ID.fullmatch(native_id) is not None,
                        f"adapter_label_invalid:{sequence_id}:object_id")
                require(native_id not in seen, f"adapter_label_invalid:{sequence_id}:duplicate_track_id")
                seen.add(native_id)
                box = item.get("box")
                require(item.get("category") in classes, f"adapter_label_invalid:{sequence_id}:class")
                require(isinstance(box, list) and len(box) == 4 and all(type(v) is int for v in box)
                        and 0 <= box[0] < box[2] <= WIDTH and 0 <= box[1] < box[3] <= HEIGHT
                        and isinstance(item.get("ignore"), bool) and isinstance(item.get("id"), str),
                        f"adapter_label_invalid:{sequence_id}:object")
                track = tracks.setdefault(item["id"], {"gtTrackId": item["id"], "nativeClass": item["category"],
                                                       "frames": []})
                require(track["nativeClass"] == item["category"], f"adapter_label_invalid:{sequence_id}:class_change")
                x1, y1, x2, y2 = box
                track["frames"].append({
                    "frameIndex": index, "videoOffsetMs": offset, "ignore": item["ignore"],
                    "box": {"x": x1 / WIDTH, "y": y1 / HEIGHT, "width": (x2 - x1) / WIDTH,
                            "height": (y2 - y1) / HEIGHT}})
        return {"sequenceId": sequence_id, "split": split, "frameSize": {"width": WIDTH, "height": HEIGHT},
                "instants": instants, "tracks": [copy.deepcopy(tracks[key]) for key in sorted(tracks)]}


def ground_truth_sha256(document: dict[str, Any]) -> str:
    """The identity the envelope binds per sequence (``groundTruthSha256``)."""
    return document_sha256(document)

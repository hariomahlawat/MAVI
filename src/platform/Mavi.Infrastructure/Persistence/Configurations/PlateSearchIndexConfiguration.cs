using Mavi.Domain.Plates;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Mavi.Infrastructure.Persistence.Configurations;

/// <summary>
/// The plate search access paths on <c>plate_track_texts</c> (Stage 4 PR-4, plan §2.8): the indexes on
/// <c>normalised_text</c> (migration <c>AddPlateSearchIndexes</c>) and the Track start time denormalised as the
/// candidate sort key (migration <c>AddPlateTextTrackStart</c>, ADR-018). Kept apart from PR-3's fact
/// configuration, which owns the table, so the lifecycle's integrity schema and the search's access paths
/// evolve separately.
/// </summary>
/// <remarks>
/// <para>
/// <b>contains</b> is <c>LIKE '%T%'</c>, which only a trigram index serves: a GIN index with the
/// <c>pg_trgm</c> contrib extension's <c>gin_trgm_ops</c>. The query text is at least three characters
/// (the shortest a trigram can be), so every contains search has at least one whole trigram.
/// </para>
/// <para>
/// <b>prefix</b> is <c>LIKE 'T%'</c> and <b>exact</b> is equality, both served by a b-tree with
/// <c>text_pattern_ops</c>, which compares bytes and so supports a left-anchored <c>LIKE</c> whatever the
/// database collation is.
/// </para>
/// <para>
/// The predicate itself uses no <c>pg_trgm</c> operator or function: without the trigram index a contains
/// search is still exact, only slower. The extension is therefore an access-path dependency, never a
/// semantic one.
/// </para>
/// <para>
/// <b>Track start (ADR-018).</b> <c>track_start_timestamp_utc</c> is a copy of the Track's own
/// <c>tracks.start_timestamp_utc</c>, maintained only by the database: a BEFORE INSERT OR UPDATE trigger
/// derives it from <c>tracks</c> in the writing transaction, and a trigger on <c>tracks</c> carries any change of
/// the start time to its texts. It is a shadow property the application never writes (store-generated; any
/// value supplied is replaced). It orders and bounds the search's candidate reads only: membership is decided
/// by the text, the analysis and the base chain, and order and keyset by <c>tracks</c> itself.
/// </para>
/// </remarks>
public sealed class PlateSearchIndexConfiguration : IEntityTypeConfiguration<PlateTrackText>
{
    public const string TrigramIndexName = "ix_plate_track_texts_normalised_text_trgm";
    public const string PatternIndexName = "ix_plate_track_texts_normalised_text_pattern";

    /// <summary>The shadow property and column of the denormalised Track start time (ADR-018).</summary>
    public const string TrackStartProperty = "TrackStartTimestampUtc";
    public const string TrackStartColumn = "track_start_timestamp_utc";

    public void Configure(EntityTypeBuilder<PlateTrackText> builder)
    {
        builder.HasIndex(x => x.NormalisedText, TrigramIndexName)
            .HasMethod("gin")
            .HasOperators("gin_trgm_ops");
        builder.HasIndex(x => x.NormalisedText, PatternIndexName)
            .HasOperators("text_pattern_ops");

        // Store-generated by the trigger of migration AddPlateTextTrackStart; EF neither sends nor updates it.
        var trackStart = builder.Property<DateTimeOffset>(TrackStartProperty)
            .HasColumnName(TrackStartColumn)
            .ValueGeneratedOnAddOrUpdate();
        trackStart.Metadata.SetBeforeSaveBehavior(PropertySaveBehavior.Ignore);
        trackStart.Metadata.SetAfterSaveBehavior(PropertySaveBehavior.Ignore);
    }
}
